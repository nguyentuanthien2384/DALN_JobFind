// Uses a fresh, uniquely named MySQL database; never truncates application tables.
const path = require('path');
const assert = require('node:assert/strict');
const { randomUUID } = require('crypto');
const mysql = require('mysql2/promise');
const { Sequelize, DataTypes } = require('sequelize');
require('dotenv').config({ path: path.join(__dirname, '../.env'), quiet: true });
require('@babel/register')({ presets: [require.resolve('@babel/preset-env')], ignore: [/node_modules/] });
const database = 'jobfind_auth_test_' + randomUUID().replace(/-/g, '');
const options = { host: process.env.DB_HOST, port: Number(process.env.DB_PORT || 3306), user: process.env.DB_USER, password: process.env.DB_PASSWORD || '' };

(async () => {
  const admin = await mysql.createConnection(options);
  let sequelize, server;
  try {
    await admin.query('CREATE DATABASE ?? CHARACTER SET utf8mb4', [database]);
    sequelize = new Sequelize(database, options.user, options.password, { host: options.host, port: options.port, dialect: 'mysql', logging: false, query: { raw: true }, pool: { max: 10 } });
    const db = { sequelize, Sequelize };
    db.Company = sequelize.define('Company', { statusCode: DataTypes.STRING, censorCode: DataTypes.STRING });
    db.User = sequelize.define('User', { firstName: DataTypes.STRING, lastName: DataTypes.STRING, email: DataTypes.STRING, companyId: DataTypes.INTEGER });
    db.Account = sequelize.define('Account', { phonenumber: DataTypes.STRING, password: DataTypes.STRING, roleCode: DataTypes.STRING, statusCode: DataTypes.STRING, userId: DataTypes.INTEGER });
    db.User.hasOne(db.Account, { foreignKey: 'userId', as: 'userAccountData' });
    db.User.belongsTo(db.Company, { foreignKey: 'companyId', as: 'userCompanyData' });
    await sequelize.sync();
    await require('../src/migrations/migrationzzzzzzz-auth-sessions-sso').up(sequelize.getQueryInterface(), DataTypes);
    await require('../src/migrations/migrationzzzzzzzz-auth-link-binding').up(sequelize.getQueryInterface(), DataTypes);
    await require('../src/migrations/migrationzzzzzzzzz-auth-audit-device').up(sequelize.getQueryInterface(), DataTypes);
    for (const [name, file] of [['AuthSession', 'authSession'], ['AuthIdentity', 'authIdentity'], ['OidcTransaction', 'oidcTransaction'], ['AuthSecurityEvent', 'authSecurityEvent']]) db[name] = require('../src/models/' + file)(sequelize, DataTypes);
    const modelsPath = require.resolve('../src/models/index');
    require.cache[modelsPath] = { id: modelsPath, filename: modelsPath, loaded: true, exports: db };
    process.env.AUTH_ALLOW_LEGACY_TOKENS = 'false';
    process.env.URL_REACT = 'http://localhost:3001';
    const sessions = require('../src/services/authSessionService');
    const controller = require('../src/controllers/authController');
    const middleware = require('../src/middlewares/jwtVerify');
    const user = await db.User.create({ firstName: 'Auth', lastName: 'Test', email: 'auth@example.invalid' });
    const password = 'Auth-integration-123!';
    await db.Account.create({ userId: user.id, phonenumber: '0900000001', password: await require('bcryptjs').hash(password, 10), statusCode: 'S1', roleCode: 'CANDIDATE' });
    const first = await sessions.createSession(user.id);
    assert.equal(first.user.roleCode, 'CANDIDATE');
    assert.equal(first.user.userAccountData, undefined);
    const jwt = require('jsonwebtoken');
    const sid = jwt.decode(first.token).sid;
    const rotated = await sessions.rotateSession(first.refreshToken);
    assert.ok(rotated && rotated.refreshToken !== first.refreshToken);
    assert.equal(await sessions.rotateSession(first.refreshToken), null);
    assert.equal(await sessions.activeFamily(sid, user.id), false);
    assert.equal(await sessions.rotateSession(rotated.refreshToken), null);
    const concurrent = await sessions.createSession(user.id);
    const competing = await Promise.all([sessions.rotateSession(concurrent.refreshToken), sessions.rotateSession(concurrent.refreshToken)]);
    assert.equal(competing.filter(Boolean).length, 1);
    assert.equal(await sessions.activeFamily(jwt.decode(concurrent.token).sid, user.id), false);
    const logoutRace = await sessions.createSession(user.id);
    await Promise.all([sessions.rotateSession(logoutRace.refreshToken), sessions.revokeByRefresh(logoutRace.refreshToken)]);
    assert.equal(await sessions.activeFamily(jwt.decode(logoutRace.token).sid, user.id), false);
    const allRace = await sessions.createSession(user.id);
    await Promise.all([sessions.rotateSession(allRace.refreshToken), sessions.revokeAll(user.id)]);
    assert.equal(await sessions.activeFamily(jwt.decode(allRace.token).sid, user.id), false);
    const changed = await sessions.createSession(user.id);
    const account = await db.Account.findOne({ where: { userId: user.id }, raw: false });
    account.password = await require('bcryptjs').hash(password, 10);
    await require('../src/services/accountSecurityService').saveAndRevokeSessions(account);
    assert.equal(await sessions.activeFamily(jwt.decode(changed.token).sid, user.id), false);
    const originalHash = account.password;
    const originalUpdate = db.AuthSession.update;
    db.AuthSession.update = async () => { throw new Error('simulated revocation outage'); };
    account.password = 'must-not-be-committed';
    try {
      await assert.rejects(require('../src/services/accountSecurityService').saveAndRevokeSessions(account), /revocation outage/);
      assert.equal((await db.Account.findOne({ where: { userId: user.id }, raw: true })).password, originalHash);
    } finally { db.AuthSession.update = originalUpdate; }
    // OIDC subject case must not collapse under the application's default collation.
    await db.AuthIdentity.create({ userId: user.id, provider: 'google', issuer: 'https://accounts.google.com', subject: 'Subject-A' });
    await db.AuthIdentity.create({ userId: user.id, provider: 'google', issuer: 'https://accounts.google.com', subject: 'subject-a' });
    assert.equal(await db.AuthIdentity.count(), 2);
    await assert.rejects(sessions.createSession(user.id, 'password', { password: 'wrong-password' }), /CREDENTIALS_CHANGED/);
    await assert.rejects(sessions.createSession(user.id, 'oidc:google', { identityId: 999999 }), /IDENTITY_REMOVED/);
    const express = require('express');
    const app = express(); app.use(express.json());
    app.post('/api/login', controller.login);
    app.post('/api/auth/refresh', controller.cookieOrigin, controller.refresh);
    app.post('/api/auth/logout', controller.cookieOrigin, middleware.verifyTokenOptional, controller.logout);
    app.get('/api/auth/me', middleware.verifyTokenUser, (req, res) => res.json({ role: req.user.userAccountData.roleCode }));
    app.get('/api/auth/security', middleware.verifyTokenUser, controller.securityOverview);
    server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
    const base = 'http://127.0.0.1:' + server.address().port;
    const headers = { 'Content-Type': 'application/json', Origin: process.env.URL_REACT };
    const denied = await fetch(base + '/api/login', { method: 'POST', headers: { ...headers, Origin: 'https://evil.invalid' }, body: JSON.stringify({ phonenumber: '0900000001', password }) });
    assert.equal(denied.status, 403);
    const login = await fetch(base + '/api/login', { method: 'POST', headers, body: JSON.stringify({ phonenumber: '0900000001', password }) });
    assert.equal(login.status, 200);
    assert.match(login.headers.get('set-cookie'), /HttpOnly/);
    assert.match(login.headers.get('set-cookie'), /SameSite=Lax/);
    const body = await login.json(); assert.ok(jwt.decode(body.token).sid);
    const cookie = login.headers.get('set-cookie').split(';')[0];
    assert.equal((await fetch(base + '/api/auth/me', { headers: { Authorization: 'Bearer ' + body.token } })).status, 200);
    const overview = await (await fetch(base + '/api/auth/security', { headers: { Authorization: 'Bearer ' + body.token } })).json();
    assert.ok(overview.sessions.some(row => row.current));
    assert.equal(JSON.stringify(overview).includes('tokenHash'), false);
    assert.equal((await fetch(base + '/api/auth/refresh', { method: 'POST', headers: { Cookie: cookie } })).status, 403);
    assert.equal((await fetch(base + '/api/auth/logout', { method: 'POST', headers: { ...headers, Cookie: cookie, Authorization: 'Bearer ' + body.token }, body: '{}' })).status, 204);
    assert.equal((await fetch(base + '/api/auth/me', { headers: { Authorization: 'Bearer ' + body.token } })).status, 401);
    assert.equal((await fetch(base + '/api/auth/refresh', { method: 'POST', headers: { ...headers, Cookie: cookie }, body: '{}' })).status, 401);
    await require('./auth/oidc-acceptance.cjs')({ db, app, base, user, headers, password });
    console.log('PASS: real MySQL migrations, login/cookies/CSRF, refresh rotation/replay, concurrent refresh/logout/logout-all, password revocation and protected HTTP endpoints.');
  } finally {
    if (server) await new Promise(resolve => server.close(resolve));
    if (sequelize) await sequelize.close();
    // The name is generated here, restricted to this script's dedicated namespace.
    if (!/^jobfind_auth_test_[a-f0-9]{32}$/.test(database)) throw new Error('Unsafe test database name');
    await admin.query('DROP DATABASE IF EXISTS ??', [database]);
    await admin.end();
  }
})().catch(error => { console.error('Auth integration failed:', error.message); process.exitCode = 1; });
